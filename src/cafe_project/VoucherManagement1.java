    private void tblDisplayVoucherMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDisplayVoucherMouseClicked
        int i = tblDisplayVoucher.getSelectedRow();
        txtIdVoucher.setText(tblDisplayVoucher.getValueAt(i, 0).toString());
        txtCode.setText(tblDisplayVoucher.getValueAt(i, 1).toString());
        txtGiamGia.setText(tblDisplayVoucher.getValueAt(i, 3).toString());
        txtSoDiemDoi.setText(tblDisplayVoucher.getValueAt(i, 4).toString());
        String Status = tblDisplayVoucher.getValueAt(i, 2).toString();

        if (Status.equals("Bật")) {
            rdoBat.setSelected(true);
            rdoTat.setSelected(false); // nếu có nút tắt
        } else {
            rdoBat.setSelected(false);
            rdoTat.setSelected(true); // hoặc bỏ dòng này nếu không cần
        }
    }//GEN-LAST:event_tblDisplayVoucherMouseClicked

