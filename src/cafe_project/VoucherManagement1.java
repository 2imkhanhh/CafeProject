    private void load_voucher(){
        try {
            con = DatabaseConnection.getConnection();
            String sql = "Select * from vouchermangement";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            DefaultTableModel tb = (DefaultTableModel)tblDisplayVoucher.getModel();
            tb.setRowCount(0);
            while(rs.next()){
                Vector vt = new Vector();
                vt.add(rs.getString("IdVoucher"));
                vt.add(rs.getString("Code"));
                vt.add(rs.getString("TrangThai"));
                vt.add(rs.getString("GiamGia"));
                vt.add(rs.getString("DiemDoi"));
                tb.addRow(vt);
            }
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(VoucherManagement1.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(VoucherManagement1.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
