    public void Delete() {
    try {
        Connection conn = ConnectSQL.getConnection();

        // Xác nhận xóa tất cả các đơn hàng có trạng thái "PAID"
        int confirm = JOptionPane.showConfirmDialog(null, 
            "Bạn có chắc chắn muốn xóa tất cả các đơn hàng có trạng thái 'PAID'?", 
            "Xác nhận xóa", 
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return; // Dừng lại nếu chọn "No"
        }

        // Lấy tất cả các đơn hàng có trạng thái "PAID" từ bảng orders
        String selectOrdersSql = "SELECT * FROM orders WHERE status = 'PAID'";
        try (PreparedStatement stmt = conn.prepareStatement(selectOrdersSql)) {
            ResultSet rs = stmt.executeQuery();
            
            while (rs.next()) {
                long orderId = rs.getLong("order_id");
                Timestamp orderTime = rs.getTimestamp("order_time");
                String status = rs.getString("status");
                long staffId = rs.getLong("staff_id");
                long tableId = rs.getLong("table_id");
                String orderType = rs.getString("order_type");

                // Chuyển đơn hàng vào bảng order_history
                String insertHistorySql = "INSERT INTO orders_history (order_id, order_time, status, staff_id, table_id, order_type) VALUES (?, ?, ?, ?, ?, ?)";
                try (PreparedStatement stmtInsert = conn.prepareStatement(insertHistorySql)) {
                    stmtInsert.setLong(1, orderId);
                    stmtInsert.setTimestamp(2, orderTime);
                    stmtInsert.setString(3, status);
                    stmtInsert.setLong(4, staffId);
                    stmtInsert.setLong(5, tableId);
                    stmtInsert.setString(6, orderType);
                    stmtInsert.executeUpdate();
                }

                // Lấy tất cả các món ăn trong bảng order_item liên quan đến orderId
                String selectItemsSql = "SELECT * FROM order_item WHERE order_id = ?";
                try (PreparedStatement stmtItems = conn.prepareStatement(selectItemsSql)) {
                    stmtItems.setLong(1, orderId);
                    ResultSet rsItems = stmtItems.executeQuery();

                    // Chuyển tất cả các món ăn vào bảng order_item_history
                    while (rsItems.next()) {
                        long menuItemId = rsItems.getLong("menu_item_id");
                        String itemName = rsItems.getString("name");
                        int quantity = rsItems.getInt("quantity");
                        double price = rsItems.getDouble("price");
                        double total = rsItems.getDouble("tongtien");

                        // Chèn vào bảng order_item_history
                        String insertItemHistorySql = "INSERT INTO order_item_history (quantity, menu_item_id, order_id, name, price, tongtien) VALUES (?, ?, ?, ?, ?, ?)";
                        try (PreparedStatement stmtItemHistory = conn.prepareStatement(insertItemHistorySql)) {
                            stmtItemHistory.setInt(1, quantity);
                            stmtItemHistory.setLong(2, menuItemId);
                            stmtItemHistory.setLong(3, orderId);
                            stmtItemHistory.setString(4, itemName);
                            stmtItemHistory.setDouble(5, price);
                            stmtItemHistory.setDouble(6, total);
                            stmtItemHistory.executeUpdate();
                        }
                    }
                }

                // Xóa các mục trong bảng order_item có liên quan đến orderId
                String deleteOrderItemsSql = "DELETE FROM order_item WHERE order_id = ?";
                try (PreparedStatement stmtDeleteItems = conn.prepareStatement(deleteOrderItemsSql)) {
                    stmtDeleteItems.setLong(1, orderId);
                    stmtDeleteItems.executeUpdate();
                }

                // Xóa đơn hàng trong bảng orders
                String deleteOrderSql = "DELETE FROM orders WHERE order_id = ?";
                try (PreparedStatement stmtDeleteOrder = conn.prepareStatement(deleteOrderSql)) {
                    stmtDeleteOrder.setLong(1, orderId);
                    stmtDeleteOrder.executeUpdate();
                }
            }

            JOptionPane.showMessageDialog(null, "Tất cả các đơn hàng 'PAID' đã được xóa và chuyển vào lịch sử!");
        }
    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Lỗi khi xóa đơn hàng: " + e.getMessage());
    }
}


    
