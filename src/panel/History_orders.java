public void Loaddata() {
    DefaultTableModel model = (DefaultTableModel) jtb1.getModel();
    model.setRowCount(0); // Xóa dữ liệu cũ

    try (Connection conn = ConnectSQL.getConnection()) {
        String sql = "SELECT * FROM orders_history";
        PreparedStatement stmt = conn.prepareStatement(sql);
        ResultSet rs = stmt.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getLong("order_id"),
                rs.getTimestamp("order_time"),
                rs.getString("status"),
                rs.getLong("staff_id"),
                rs.getLong("table_id"),
                rs.getString("order_type")
            });
        }



    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Lỗi tải dữ liệu: " + e.getMessage());
    }
}
private void timKiemTheoNgay() {
    java.util.Date selectedDate = jDateChooser1.getDate();

    if (selectedDate == null) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn ngày cần tìm!");
        return;
    }

    java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String formattedDate = sdf.format(selectedDate);

    DefaultTableModel model = (DefaultTableModel) jtb1.getModel();
    model.setRowCount(0); // Xóa dữ liệu cũ

    try (Connection conn = ConnectSQL.getConnection()) {
        String sql = "SELECT * FROM orders_history WHERE DATE(order_time) = ?";
        PreparedStatement stmt = conn.prepareStatement(sql);
        stmt.setString(1, formattedDate);
        ResultSet rs = stmt.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[] {
                rs.getLong("order_id"),
                rs.getTimestamp("order_time"),
                rs.getString("status"),
                rs.getLong("staff_id"),
                rs.getLong("table_id"),
                rs.getString("order_type")
            });
        }

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Không có đơn hàng nào vào ngày " + formattedDate);
        }

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Lỗi khi tìm kiếm: " + e.getMessage());
    }
}
    
