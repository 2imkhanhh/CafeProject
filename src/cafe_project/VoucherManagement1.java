    private boolean isEmptyVoucherInput(String id, String code, String discount, String pointText, JRadioButton rdoBat, JRadioButton rdoTat) {
        if (id == null || id.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Mã voucher!");
            return true;
        }
        if (code == null || code.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Code!");
            return true;
        }
        if (discount == null || discount.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Giảm giá!");
            return true;
        }
        if (pointText == null || pointText.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập số điểm đổi!");
            return true;
        }
        try {
            Integer.parseInt(pointText.trim()); // Kiểm tra có phải số không
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số điểm đổi phải là số!");
            return true;
        }
        if (!rdoBat.isSelected() && !rdoTat.isSelected()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Trạng thái!");
            return true;
        }
        return false;
    }
    private boolean CheckTrung(String idVoucher, String code) {
    try {
        String sql = "SELECT COUNT(*) FROM vouchermangement WHERE IdVoucher = ? OR Code = ?";
        PreparedStatement ps = con.prepareStatement(sql);
        ps.setString(1, idVoucher);
        ps.setString(2, code);
        ResultSet rs = ps.executeQuery();
        if (rs.next()) {
            return rs.getInt(1) > 0;
        }
    } catch (SQLException ex) {
        Logger.getLogger(VoucherManagement1.class.getName()).log(Level.SEVERE, null, ex);
    }
    return false;
    }

    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        try {
            String IdVoucher = txtIdVoucher.getText();
            String Code = txtCode.getText().trim();
            String GiamGia = txtGiamGia.getText();
            String DiemDoiText = txtSoDiemDoi.getText().trim();
            if (isEmptyVoucherInput(IdVoucher, Code, GiamGia, DiemDoiText, rdoBat, rdoTat)) {
                return;
            }
            int DiemDoi = Integer.parseInt(DiemDoiText);
            String Status;
            if(rdoBat.isSelected()){
                Status = rdoBat.getText();
            }
            else{
                Status = rdoTat.getText();
            }
            if (CheckTrung(IdVoucher, Code)) {
                JOptionPane.showMessageDialog(this, "Mã voucher hoặc Code đã tồn tại!");
                return;
            }
            String sql = "Insert vouchermangement values(?,?,?,?,?)";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, IdVoucher);
            ps.setString(2, Code);
            ps.setString(3,Status);
            ps.setString(4, GiamGia);
            ps.setInt(5, DiemDoi);
            ps.executeUpdate();
            load_voucher();
            JOptionPane.showMessageDialog(this, "Thêm mới thành công");
        } catch (SQLException ex) {
            Logger.getLogger(TableManagement1.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnLuuActionPerformed

