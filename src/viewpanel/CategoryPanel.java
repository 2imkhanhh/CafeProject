    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // 1. Lấy từ khóa tìm kiếm
        String keyword = txtSearch.getText().trim();
        if (keyword.isEmpty()) {
            // Nếu không nhập gì, có thể load lại toàn bộ dữ liệu
            loadData();
            return;
        }

        // 2. Gọi DAO để tìm category theo tên
        List<Category> resultList = categoryDAO.searchCategoriesByName(keyword);

        // 3. Xóa dữ liệu cũ trên tableModel
        tableModel.setRowCount(0);

        // 4. Đổ dữ liệu tìm được lên bảng
        for (Category c : resultList) {
            tableModel.addRow(new Object[]{c.getId(), c.getName()});
        }

        // 5. Xóa các trường nhập liệu (nếu cần)
        textIdCategory.setText("");
        textNameCategory.setText("");

        // 6. Xóa panel món (nếu đang hiển thị)
        jItemsPanel.removeAll();
        jItemsPanel.revalidate();
        jItemsPanel.repaint();
    }//GEN-LAST:event_btnSearchActionPerformed


