    public int getNextIdTable() {
        int nextId = 1; // mặc định nếu bảng rỗng
        try {
            con = DatabaseConnection.getConnection();
            String sql = "SELECT IFNULL(MAX(IdTable), 0) + 1 AS NextID FROM tablemanagement";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                nextId = rs.getInt("NextID");
            }
        } catch (SQLException ex) {
            Logger.getLogger(TableManagement1.class.getName()).log(Level.SEVERE, null, ex);
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(TableManagement1.class.getName()).log(Level.SEVERE, null, ex);
        }
        return nextId;
    }


    private void load_Table(){
        try {
            con = DatabaseConnection.getConnection();
            String sql = "Select * From tablemanagement";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            DefaultTableModel tb = (DefaultTableModel) tblDisplayTable.getModel();
            tb.setRowCount(0);
            while(rs.next()){
                Vector vt = new Vector();
                vt.add(rs.getString("IdTable"));
                vt.add(rs.getString("TableName"));
                vt.add(rs.getString("Area"));
                vt.add(rs.getString("Status"));
                tb.addRow(vt);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
