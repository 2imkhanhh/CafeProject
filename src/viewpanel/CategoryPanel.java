    private void jCategoryTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jCategoryTableMouseClicked
        int selectrow=jCategoryTable.getSelectedRow();
        if(selectrow!=-1){
            Object idObj=jCategoryTable.getValueAt(selectrow, 0);
            Object name=jCategoryTable.getValueAt(selectrow, 1);
            textIdCategory.setText(String.valueOf(idObj));
            textNameCategory.setText(String.valueOf(name));
            long id = Long.parseLong(String.valueOf(idObj));
            loadMenuItems(id);
        }
    }//GEN-LAST:event_jCategoryTableMouseClicked

    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        String nameCategory=textNameCategory.getText();

        if (nameCategory == null || nameCategory.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Tên danh mục không được để trống!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }
        nameCategory = nameCategory.trim();
        if (nameCategory.length() > 255) {
            JOptionPane.showMessageDialog(null, "Tên danh mục không được vượt quá " + 255 + " ký tự!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }
        categoryDAO.insertCategory(nameCategory);
        loadData();
        textNameCategory.setText("");
        textIdCategory.setText("");
    }//GEN-LAST:event_btnaddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        long id =Long.parseLong(textIdCategory.getText());
        String nameCategory=textNameCategory.getText();
        if (nameCategory == null || nameCategory.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Tên danh mục không được để trống!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }
        nameCategory = nameCategory.trim();
        if (nameCategory.length() > 255) {
            JOptionPane.showMessageDialog(null, "Tên danh mục không được vượt quá " + 255 + " ký tự!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }
        categoryDAO.updateCategory(id, nameCategory);
        loadData();
        textNameCategory.setText("");
        textIdCategory.setText("");
    }//GEN-LAST:event_btnUpdateActionPerformed

