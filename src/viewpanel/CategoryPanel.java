    private void loadMenuItems(long categoryId) {
        jItemsPanel.removeAll();
        List<MenuItem> items = menuItemDAO.getMenuItemsByCategory(categoryId);
        int cardSize = 110;
        for (MenuItem m : items) {
            JPanel card = new JPanel();
            card.setPreferredSize(new Dimension(cardSize, cardSize));
            card.setLayout(new BoxLayout(card, BoxLayout.Y_AXIS));
            card.setBorder(BorderFactory.createLineBorder(java.awt.Color.GRAY));
            String imgData = m.getImageUrl();
            ImageIcon icon = createIcon(imgData, 60, 60);
            JLabel lblImage = new JLabel(icon);
            lblImage.setAlignmentX(CENTER_ALIGNMENT);
            JLabel lblName = new JLabel(m.getName());
            lblName.setAlignmentX(CENTER_ALIGNMENT);
            JLabel lblPrice = new JLabel(String.format("%,d VNĐ", m.getPrice().longValue()));
            lblPrice.setAlignmentX(CENTER_ALIGNMENT);
            card.add(Box.createVerticalStrut(5));
            card.add(lblImage);
            card.add(Box.createVerticalStrut(5));
            card.add(lblName);
            card.add(Box.createVerticalStrut(3));
            card.add(lblPrice);
            jItemsPanel.add(card);
        }
        jItemsPanel.revalidate();
        jItemsPanel.repaint();
    }
    
    private ImageIcon createIcon(String data, int w, int h) {
        try {
            BufferedImage buf;
            if (data.startsWith("data:image")) {
                byte[] bytes = Base64.getDecoder().decode(data.substring(data.indexOf(",")+1));
                buf = ImageIO.read(new ByteArrayInputStream(bytes));
            } else {
                buf = ImageIO.read(new URL(data));
            }
            Image scaled = buf.getScaledInstance(w, h, Image.SCALE_SMOOTH);
            return new ImageIcon(scaled);
        } catch (Exception ex) {
            BufferedImage fallback = new BufferedImage(w, h, BufferedImage.TYPE_INT_RGB);
            return new ImageIcon(fallback);
        }
    }
    
