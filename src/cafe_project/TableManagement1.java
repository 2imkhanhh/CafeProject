    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        try {
            int i = tblDisplayTable.getSelectedRow();
            if(i == -1){
                JOptionPane.showMessageDialog(this, "Bạn vui lòng chọn dòng cần xóa");
                return;
            }
            else{
                int result = JOptionPane.showConfirmDialog(this, "Bạn có chắn chắn muốn xóa không", "Xóa",JOptionPane.YES_NO_OPTION );
                if(result == JOptionPane.NO_OPTION){
                    return;
                }
                else {
                    int IdTable = Integer.parseInt(txtIdTable.getText());
                    String sql = "Delete from tablemanagement where IdTable = ?";
                    PreparedStatement ps = con.prepareStatement(sql);
                    ps.setInt(1, IdTable);
                    ps.executeUpdate();
                    load_Table();
                    JOptionPane.showMessageDialog(this, "Xóa thành công");
                }
            }
        } catch (SQLException ex) {
            Logger.getLogger(TableManagement1.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

