    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (Loirong()) {
            return;
        }
        // Kiểm tra trạng thái trong jcb1
        String selectedStatus = jcb1.getSelectedItem().toString().trim();  // Lấy trạng thái từ JComboBox
        if (!"PENDING".equals(selectedStatus)) {
            // Nếu không phải "PENDING", hiển thị thông báo cảnh báo
            JOptionPane.showMessageDialog(null, "Bạn phải chọn trạng thái 'PENDING' để thêm đơn hàng!",
                "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;  // Dừng lại không thực hiện thêm đơn hàng
        }

        // Kiểm tra nếu id đã tồn tại
        if (isIdExist()) {
            JOptionPane.showMessageDialog(null, "ID đã tồn tại!");
            return;
        }

        // Kiểm tra nếu bàn đã được chọn và đang sử dụng
        Object selectedItem = jcb3.getSelectedItem();
        if (selectedItem != null) {
            long selectedTableId = Long.parseLong(selectedItem.toString().trim());

            if (isTableAlreadyUsed(selectedTableId)) {
                JOptionPane.showMessageDialog(this, "Bàn này đã được sử dụng, vui lòng chọn bàn khác!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                return; // Dừng lại không thực hiện thêm đơn hàng
            }
        }
        // Nếu selectedItem == null thì bỏ qua kiểm tra và tiếp tục xử lý đơn hàng

        // Thêm đơn hàng nếu tất cả kiểm tra hợp lệ
        ADD();
        Loaddata();
        //loadOrdersData(); // Tải lại dữ liệu sau khi thêm đơn hàng TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jtb1.getSelectedRow();

        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng để sửa", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Lấy table_id hiện tại từ dòng đã chọn
        long currentTableId = Long.parseLong(jtb1.getValueAt(selectedRow, 4).toString());

        // Lấy table_id mới được chọn từ combobox
        Object selectedItem = jcb3.getSelectedItem();
        if (selectedItem != null) {
            long newTableId = Long.parseLong(selectedItem.toString().trim());

            // Nếu người dùng đổi bàn => mới kiểm tra bàn có đang sử dụng không
            if (newTableId != currentTableId) {
                if (isTableAlreadyUsed(newTableId)) {
                    JOptionPane.showMessageDialog(this, "Bàn này đã được sử dụng, vui lòng chọn bàn khác!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
        }

        // Gọi hàm cập nhật đơn hàng
        UpdateOrder();

        // Kiểm tra lỗi rỗng
        if (Loirong()) {
            return;
        }

        // Load lại dữ liệu
        Loaddata();
    }//GEN-LAST:event_jButton2ActionPerformed

