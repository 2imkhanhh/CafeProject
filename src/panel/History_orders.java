    private void setRowHeight(JTable table) {
    for (int row = 0; row < table.getRowCount(); row++) {
        int rowHeight = 0;
        for (int column = 0; column < table.getColumnCount(); column++) {
            TableCellRenderer renderer = table.getCellRenderer(row, column);
            Component comp = table.prepareRenderer(renderer, row, column);
            rowHeight = Math.max(rowHeight, comp.getPreferredSize().height);
        }
        table.setRowHeight(row, rowHeight);
    }
    }
    private void loadOrderDetailsByOrderId(long orderId) {
    DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
    tableModel.setRowCount(0);  // Xóa dữ liệu cũ

    try (Connection conn = ConnectSQL.getConnection()) {
        String query = "SELECT * FROM order_item_history WHERE order_id = ?";
        try (PreparedStatement stmt = conn.prepareStatement(query)) {
            stmt.setLong(1, orderId);
            ResultSet rs = stmt.executeQuery();

            StringBuilder items = new StringBuilder();
            StringBuilder quantities = new StringBuilder();
            StringBuilder prices = new StringBuilder();
            StringBuilder menuItemIds = new StringBuilder();
            double totalAmount = 0;

            while (rs.next()) {
                long menuItemId = rs.getLong("menu_item_id");
                String name = rs.getString("name");
                int quantity = rs.getInt("quantity");
                double price = rs.getDouble("price");

                items.append(name).append("\n");
                quantities.append(quantity).append("\n");
                prices.append(price).append("\n");
                menuItemIds.append(menuItemId).append("\n");
                totalAmount += price * quantity;
            }

            if (items.length() > 0) {
                tableModel.addRow(new Object[]{
                    quantities.toString(),
                    menuItemIds.toString(),
                    orderId,
                    items.toString(),
                    prices.toString(),
                    totalAmount
                });
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }
    } catch (SQLException e) {
        e.printStackTrace();
    }

    jTable1.setModel(tableModel);
    jTable1.setDefaultRenderer(Object.class, new MultiLineCellRenderer());
    setRowHeight(jTable1);
}

