 private void loadRevenueChart(String condition, String value) {
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();
        String sql = "SELECT date, TotalAmount FROM revenues";
        if (condition != null) {
            sql += " WHERE " + condition;
        }
        sql += " ORDER BY date";

        try (Connection conn = ConnectSQL.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {
            if (value != null) stmt.setString(1, value);
            ResultSet rs = stmt.executeQuery();

            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            while (rs.next()) {
                Date date = rs.getDate("date");
                double total = rs.getDouble("TotalAmount");
                dataset.addValue(total, "Doanh thu", sdf.format(date));
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi truy vấn: " + e.getMessage());
            return;
        }

        JFreeChart chart = ChartFactory.createBarChart(
            "Thống kê Doanh thu",
            "Ngày",
            "Tổng tiền (VND)",
            dataset,
            PlotOrientation.VERTICAL,
            false, true, false
        );

        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setPreferredSize(new Dimension(850, 450));
        chartPanelContainer.removeAll();
        chartPanelContainer.add(chartPanel, BorderLayout.CENTER);
        chartPanelContainer.revalidate();
        chartPanelContainer.repaint();
    }
