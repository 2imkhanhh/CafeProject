    private void exportRevenueToCSV() {
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Lưu doanh thu thành file CSV");
        int result = fileChooser.showSaveDialog(this);

        if (result == JFileChooser.APPROVE_OPTION) {
            try (Connection conn = ConnectSQL.getConnection();
                 PreparedStatement stmt = conn.prepareStatement("SELECT date, TotalAmount FROM revenues ORDER BY date");
                 ResultSet rs = stmt.executeQuery()) {

                java.io.File file = fileChooser.getSelectedFile();
                if (!file.getName().toLowerCase().endsWith(".csv")) {
                    file = new java.io.File(file.getAbsolutePath() + ".csv");
                }

                try (java.io.FileWriter writer = new java.io.FileWriter(file)) {
                    writer.write("Ngày,Tổng tiền (VND)\n");
                    SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

                    while (rs.next()) {
                        String date = sdf.format(rs.getDate("date"));
                        double total = rs.getDouble("TotalAmount");
                        writer.write(date + "," + total + "\n");
                    }

                    JOptionPane.showMessageDialog(this, "Xuất file thành công!");
                }

            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Lỗi khi xuất file: " + e.getMessage());
            }
        }
    }

